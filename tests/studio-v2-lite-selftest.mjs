import assert from 'node:assert/strict';
import fs from 'node:fs';
const js=fs.readFileSync('studio-v2-lite.js','utf8');
const html=fs.readFileSync('studio-v2.html','utf8');
const groq=fs.readFileSync('studio-v2-groq.js','utf8');
const prompts=fs.readFileSync('studio-v2-prompts.js','utf8');
assert.match(html,/Ridge Studio V2\.6/);
assert.match(html,/Pexels Photos/);assert.match(html,/Pexels Videos/);
assert.ok(!/Pexels key/i.test(html),'Pexels API key should be removed from the lean UI');
assert.match(js,/showDirectoryPicker/);assert.match(js,/Import newest downloads|importNewest/);
assert.match(js,/https:\/\/www\.pexels\.com\/search/);
assert.ok(!/PexelsClient/.test(js),'lean flow must not call Pexels API client');
assert.equal((js.match(/id:'naru-/g)||[]).length,6,'six Naru original ninja/anime themes expected');
for(const style of ['phonk','hyper','naru','rain','dream','mythic','clean'])assert.ok(js.includes(`${style}:{name:`),`missing edit style ${style}`);
for(const style of ['cinematic','karaoke','kinetic','wordpop','glitch','manga','outline','vertical'])assert.match(js,new RegExp(`${style}:`));
assert.match(js,/detectBeat/);assert.match(js,/glitch/);assert.match(js,/shake/);assert.match(js,/flash/);assert.match(js,/lines/);
assert.match(js,/createOpfsWriter/);assert.match(js,/SceneManager/);assert.match(js,/uploadYouTubeResumable/);
for(const key of ['"edit_profile"','"lyric_animation"','"thumbnail_style"','"pexels_queries"'])assert.ok(prompts.includes(key),`prompt schema missing ${key}`);
assert.match(groq,/buildAnalysisPrompt/);assert.match(groq,/buildPolishPrompt/);
assert.ok(!/suno.*password|password.*suno|suno.*cookie|cookie.*suno/i.test(js),'no Suno credential automation');
const ids=new Set([...html.matchAll(/\bid=["']([^"']+)["']/g)].map(x=>x[1]));
const refs=new Set([...js.matchAll(/\$\(['"]#([A-Za-z0-9_-]+)['"]\)/g)].map(x=>x[1]));
const missing=[...refs].filter(x=>!ids.has(x));assert.deepEqual(missing,[],`missing DOM ids: ${missing.join(', ')}`);
console.log(`studio-v2-lite-selftest: PASS — ${ids.size} ids, 6 Naru themes, 7 edit profiles, Pexels folder workflow`);