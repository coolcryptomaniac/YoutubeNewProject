import assert from 'node:assert/strict';
import fs from 'node:fs';
const js=fs.readFileSync('studio-v2-lite.js','utf8');
const html=fs.readFileSync('studio-v2.html','utf8');
const groq=fs.readFileSync('studio-v2-groq.js','utf8');
const prompts=fs.readFileSync('studio-v2-prompts.js','utf8');
assert.match(html,/Ridge Studio V2\.7/);
assert.match(html,/CREATE VIDEO/);assert.match(html,/Advanced controls/);
assert.match(html,/Pexels Photos/);assert.match(html,/Pexels Videos/);
assert.ok(!/Pexels key/i.test(html),'Pexels API key should not return to simple UI');
assert.match(js,/showDirectoryPicker/);assert.match(js,/importNewest/);assert.match(js,/https:\/\/www\.pexels\.com\/search/);
assert.equal((js.match(/id:'naru-/g)||[]).length,8,'eight original Naru themes expected');
for(const style of ['balanced','phonk','hyper','naru','rain','dream','mythic','clean'])assert.ok(js.includes(`${style}:{name:`),`missing edit style ${style}`);
for(const style of ['cinematic','karaoke','kinetic','wordpop','glitch','manga','outline','vertical','chakra','slash','subtitle'])assert.match(js,new RegExp(`${style}:`));
assert.match(js,/effectLane/);assert.match(js,/S\.beat\.count%4/);assert.match(js,/time-S\.beat\.last>\.31/);assert.match(js,/Math\.max\(\.85,edit\(\)\.cut\)/);
assert.match(js,/maxDecoded:memGB<=3\?1:2/);assert.match(js,/scene limit reached \(18\)/i);assert.match(js,/prefetchAt/);
assert.match(js,/createOpfsWriter/);assert.match(js,/uploadYouTubeResumable/);assert.match(js,/proceduralNaru/);
for(const key of ['"edit_profile"','"lyric_animation"','"thumbnail_style"','"pexels_queries"'])assert.ok(prompts.includes(key),`prompt schema missing ${key}`);
assert.match(groq,/buildMeaningPrompt/);assert.match(groq,/buildAnalysisPrompt/);assert.match(groq,/canonical_meaning/);
const ids=new Set([...html.matchAll(/\bid=["']([^"']+)["']/g)].map(x=>x[1]));
const refs=new Set([...js.matchAll(/\$\(['"]#([A-Za-z0-9_-]+)['"]\)/g)].map(x=>x[1]));
const missing=[...refs].filter(x=>!ids.has(x));assert.deepEqual(missing,[],`missing DOM ids: ${missing.join(', ')}`);
assert.ok(!/suno.*password|password.*suno|suno.*cookie|cookie.*suno/i.test(js),'no Suno credential automation');
console.log(`studio-v2-lite-selftest: PASS — V2.7 ${ids.size} ids, 8 Naru packs, stable effect budget, mobile memory caps`);
